-- PostgreSQL initialization script for Deanery Statement App.
-- Run from psql while connected to the default database, for example:
-- psql -U postgres -f sql/init_db.sql

SELECT 'CREATE DATABASE deanery_statement_app WITH ENCODING ''UTF8'' TEMPLATE template0'
WHERE NOT EXISTS (
    SELECT 1 FROM pg_database WHERE datname = 'deanery_statement_app'
)\gexec

\connect deanery_statement_app

CREATE TABLE IF NOT EXISTS subjects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS student_groups (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS specialties (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS teachers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS semesters (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS academic_years (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS control_forms (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS department_heads (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS grade_rules (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    min_percent NUMERIC(5,2) NOT NULL,
    max_percent NUMERIC(5,2) NOT NULL,
    grade_number INTEGER NOT NULL,
    grade_short VARCHAR(20) NOT NULL,
    grade_full VARCHAR(100) NOT NULL,
    CONSTRAINT uq_grade_rules_range UNIQUE (min_percent, max_percent)
);

CREATE INDEX IF NOT EXISTS idx_grade_rules_range
ON grade_rules (min_percent, max_percent);

CREATE TABLE IF NOT EXISTS generated_statements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_name VARCHAR(255),
    group_name VARCHAR(100),
    specialty_name VARCHAR(255),
    teacher_name VARCHAR(255),
    source_excel_file VARCHAR(500),
    output_docx_file VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

